const DICT: Record<Lang, Record<Key, string>> = { en, ru };

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = DICT[current][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

// ─── Plurals (days) ───────────────────────────────────────────────────────────

export function daysWord(n: number): string {
  if (current === 'en') return n === 1 ? 'day' : 'days';
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return 'день';
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return 'дня';
  return 'дней';
}

export function paymentsWord(n: number): string {
  if (current === 'en') return n === 1 ? 'payment' : 'payments';
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return 'платёж';
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return 'платежа';
  return 'платежей';
}

